INK = '#101013'

class Mark(QWidget):
    def __init__(self):
        super().__init__()
        self.setFixedSize(32, 32)
    def paintEvent(self, event):
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        painter.setPen(Qt.PenStyle.NoPen)
        painter.setBrush(QColor('#e65c56'))
        path = QPainterPath()
        path.moveTo(3, 24)
        path.cubicTo(3, 3, 29, 3, 29, 24)
        path.cubicTo(27, 29, 5, 29, 3, 24)
        painter.drawPath(path)


