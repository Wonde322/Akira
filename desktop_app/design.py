def refresh(window):
    if not hasattr(window, 'history'): return
    window.history.blockSignals(True)
    window.history.clear()
    for i in range(window.chat_selector.count()):
        title = window.chat_selector.itemText(i)
        item = QListWidgetItem(title)
        item.setToolTip(title)
        item.setSizeHint(QSize(174, 44))
        window.history.addItem(item)
    window.history.setCurrentRow(window.chat_selector.currentIndex())
    window.history.blockSignals(False)
    window.page_title.setText(window.chat_selector.currentText()[:45])
    empty = not window.chat_store.get()['messages']
    window.welcome.setVisible(empty)
    window.core.setMaximumHeight(220 if empty else 150)
